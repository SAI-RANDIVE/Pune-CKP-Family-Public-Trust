/** Newest first; undated entries last. */
export const EVENTS_NEWEST_FIRST = EVENTS
  .map((event, index) => ({ event, index }))
  .sort((a, b) => ((b.event.year || 0) - (a.event.year || 0)) || (b.index - a.index))
  .map(({ event }) => event);

